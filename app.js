function detectLanguage() {

    const language =
        String(
            navigator.language ||
            "en"
        ).toLowerCase();

    if (
        language.startsWith("ar")
    ) {
        return "ar";
    }

    if (
        language.startsWith("fr")
    ) {
        return "fr";
    }

    if (
        language.startsWith("ja")
    ) {
        return "ja";
    }

    return "en";

}


function translateText(value) {

    const language =
        ASEM.state.language;

    const dictionary =
        TRANSLATIONS[language] ||
        TRANSLATIONS.en;

    return dictionary[value] ||
        value;

}


function translateDocument() {

    const dictionary =
        TRANSLATIONS[
            ASEM.state.language
        ] || TRANSLATIONS.en;

    const walker =
        document.createTreeWalker(
            document.body,
            NodeFilter.SHOW_TEXT
        );

    const nodes = [];

    let node;

    while (
        (node = walker.nextNode())
    ) {

        nodes.push(node);

    }

    nodes.forEach(node => {

        const original =
            node.nodeValue.trim();

        if (!original) {
            return;
        }

        if (
            dictionary[
                original
            ]
        ) {

            node.nodeValue =
                node.nodeValue.replace(
                    original,
                    dictionary[original]
                );

        }

    });

    $$(
        "input[placeholder]"
    ).forEach(input => {

        const original =
            input.getAttribute(
                "placeholder"
            );

        if (
            dictionary[
                original
            ]
        ) {

            input.setAttribute(
                "placeholder",
                dictionary[original]
            );

        }

    });

}


function applyLanguage(language) {

    const selected =
        language === "auto"
            ? detectLanguage()
            : (
                [
                    "ar",
                    "en",
                    "fr",
                    "ja"
                ].includes(language)
                    ? language
                    : "en"
            );

    ASEM.state.language =
        selected;

    ROOT.setAttribute(
        "lang",
        selected
    );

    ROOT.setAttribute(
        "dir",
        selected === "ar"
            ? "rtl"
            : "ltr"
    );

    try {

        localStorage.setItem(
            ASEM.storage.language,
            language || selected
        );

    } catch {}

    const selector =
        $(ASEM.selectors.language);

    if (selector) {

        const exists =
            Array.from(
                selector.options
            ).some(
                option =>
                    option.value === language
            );

        if (exists) {
            selector.value =
                language;
        }

    }

    translateDocument();

    document.dispatchEvent(
        new CustomEvent(
            "asem:languagechange",
            {
                detail: {
                    language: selected
                }
            }
        )
    );

    return selected;

}


function initializeLanguage() {

    let saved =
        "auto";

    try {

        saved =
            localStorage.getItem(
                ASEM.storage.language
            ) || "auto";

    } catch {}

    const selector =
        $(ASEM.selectors.language);

    if (selector) {

        const exists =
            Array.from(
                selector.options
            ).some(
                option =>
                    option.value === saved
            );

        if (exists) {

            selector.value =
                saved;

        }

    }

    applyLanguage(
        selector?.value ||
        saved
    );

}


