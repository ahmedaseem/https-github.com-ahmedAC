function applyTheme(theme) {

    const valid =
        theme === "dark"
            ? "dark"
            : "light";

    ROOT.setAttribute(
        "data-theme",
        valid
    );

    const button =
        $(ASEM.selectors.theme);

    if (button) {

        button.textContent =
            valid === "dark"
                ? "☀️"
                : "🌙";

        button.setAttribute(
            "aria-label",
            valid === "dark"
                ? "Switch to light mode"
                : "Switch to dark mode"
        );

    }

    try {

        localStorage.setItem(
            ASEM.storage.theme,
            valid
        );

    } catch {}

    return valid;

}


function initializeTheme() {

    let saved = null;

    try {

        saved =
            localStorage.getItem(
                ASEM.storage.theme
            );

    } catch {}

    if (
        saved === "dark" ||
        saved === "light"
    ) {

        applyTheme(saved);
        return;

    }

    const dark =
        window.matchMedia &&
        window.matchMedia(
            "(prefers-color-scheme: dark)"
        ).matches;

    applyTheme(
        dark
            ? "dark"
            : "light"
    );

}


function toggleTheme() {

    const current =
        ROOT.getAttribute(
            "data-theme"
        );

    applyTheme(
        current === "dark"
            ? "light"
            : "dark"
    );

}


function initializeThemeEvents() {

    const button =
        $(ASEM.selectors.theme);

    if (!button) {
        return;
    }

    button.addEventListener(
        "click",
        toggleTheme
    );

}


