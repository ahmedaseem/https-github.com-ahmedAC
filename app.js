/* ========================================================
   RENDER
======================================================== */

function renderGrid(
    grid,
    items,
    builder,
    emptyTitle,
    emptyMessage
) {

    if (!grid) {
        return;
    }

    if (!Array.isArray(items)) {
        items = [];
    }

    if (!items.length) {

        setGridEmpty(
            grid,
            emptyTitle,
            emptyMessage
        );

        return;

    }

    grid.innerHTML =
        items
            .map(
                item => {

                    try {
                        return builder(item || {});
                    } catch (error) {

                        console.error(
                            "ASEM card render error",
                            error
                        );

                        return "";

                    }

                }
            )
            .filter(Boolean)
            .join("");

    grid.setAttribute(
        "aria-busy",
        "false"
    );

}


