function escapeHTML(value) {

    if (
        value === null ||
        value === undefined
    ) {
        return "";
    }

    return String(value)
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#039;");

}


function safeURL(value) {

    if (!value) {
        return "";
    }

    try {

        const url =
            new URL(
                String(value),
                window.location.href
            );

        const allowed =
            [
                "http:",
                "https:",
                "mailto:",
                "tel:"
            ];

        if (
            !allowed.includes(
                url.protocol
            )
        ) {
            return "";
        }

        return url.href;

    } catch {

        return "";

    }

}


function text(value, fallback = "") {

    if (
        value === null ||
        value === undefined ||
        value === ""
    ) {
        return fallback;
    }

    return String(value);

}


/* ========================================================
   ARRAY NORMALIZATION
======================================================== */

function normalizeArray(data) {

    if (Array.isArray(data)) {
        return data;
    }

    if (
        !data ||
        typeof data !== "object"
    ) {
        return [];
    }

    const keys = [

        "data",
        "items",
        "results",
        "records",
        "tourism",
        "businesses",
        "products",
        "projects",
        "destinations",
        "services"

    ];

    for (
        const key of keys
    ) {

        if (
            Array.isArray(
                data[key]
            )
        ) {
            return data[key];
        }

    }

    return [];

}


