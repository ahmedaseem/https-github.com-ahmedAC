/* ========================================================
   GPS / GEOLOCATION
======================================================== */

function requestGPS() {

    if (
        !("geolocation" in navigator)
    ) {

        showLocationStatus(
            "Geolocation is not supported by this browser."
        );

        return;

    }

    showLocationStatus(
        "Requesting your location..."
    );

    navigator.geolocation.getCurrentPosition(

        position => {

            const location = {

                latitude:
                    position.coords.latitude,

                longitude:
                    position.coords.longitude,

                accuracy:
                    position.coords.accuracy,

                timestamp:
                    Date.now()

            };

            ASEM.state.location =
                location;

            try {

                localStorage.setItem(
                    ASEM.storage.location,
                    JSON.stringify(
                        location
                    )
                );

            } catch {}

            showLocationStatus(
                `Location acquired (${location.latitude.toFixed(5)}, ${location.longitude.toFixed(5)})`
            );

            document.dispatchEvent(
                new CustomEvent(
                    "asem:locationchange",
                    {
                        detail:
                            location
                    }
                )
            );

            sendLocationToBackend(
                location
            );

        },

        error => {

            let message =
                "Unable to obtain location.";

            if (
                error.code ===
                error.PERMISSION_DENIED
            ) {

                message =
                    "Location permission was denied.";

            } else if (
                error.code ===
                error.POSITION_UNAVAILABLE
            ) {

                message =
                    "Location is currently unavailable.";

            } else if (
                error.code ===
                error.TIMEOUT
            ) {

                message =
                    "Location request timed out.";

            }

            console.warn(
                "ASEM GPS:",
                error
            );

            showLocationStatus(
                message
            );

        },

        {

            enableHighAccuracy:
                true,

            timeout:
                15000,

            maximumAge:
                0

        }

    );

}


function showLocationStatus(
    message
) {

    const elements =
        $$(
            "[data-asem-location-status]"
        );

    elements.forEach(
        element => {

            element.textContent =
                message || "";

        }
    );

}


async function sendLocationToBackend(
    location
) {

    if (
        !ASEM.api.location
    ) {
        return;
    }

    try {

        await apiRequest(
            ASEM.api.location,
            {

                method:
                    "POST",

                body:
                    location

            }
        );

    } catch (error) {

        console.warn(
            "ASEM location backend:",
            error
        );

    }

}


/* ========================================================
   COPY
======================================================== */

async function copyText(
    value,
    button = null
) {

    if (!value) {
        return false;
    }

    try {

        if (
            navigator.clipboard &&
            window.isSecureContext
        ) {

            await navigator.clipboard.writeText(
                value
            );

        } else {

            const area =
                document.createElement(
                    "textarea"
                );

            area.value =
                value;

            area.style.position =
                "fixed";

            area.style.opacity =
                "0";

            document.body.appendChild(
                area
            );

            area.focus();

            area.select();

            document.execCommand(
                "copy"
            );

            area.remove();

        }

        if (button) {

            const original =
                button.textContent;

            button.textContent =
                translateText(
                    "Copied ✓"
                );

            setTimeout(
                () => {

                    button.textContent =
                        original;

                },
                1500
            );

        }

        return true;

    } catch (error) {

        console.error(
            "ASEM copy:",
            error
        );

        window.prompt(
            "Copy this text:",
            value
        );

        return false;

    }

}


