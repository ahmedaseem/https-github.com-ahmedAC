function getImage(item) {

    return (
        item.image ||
        item.cover_image ||
        item.logo ||
        item.thumbnail ||
        ""
    );

}


function getName(item, fallback) {

    return (
        item.name ||
        item.title ||
        item.business_name ||
        item.product_name ||
        fallback
    );

}


function getDescription(
    item,
    fallback
) {

    return (
        item.description ||
        item.summary ||
        item.excerpt ||
        fallback
    );

}


function makeCopyData(
    parts
) {

    return parts
        .filter(
            value =>
                value !== null &&
                value !== undefined &&
                value !== ""
        )
        .join("\n");

}


function imageHTML(
    image,
    name,
    icon
) {

    const url =
        safeURL(image);

    if (!url) {

        return `

            <div
                class="platform-card-icon"
                aria-hidden="true">
                ${icon}
            </div>

        `;

    }

    return `

        <img
            src="${escapeHTML(url)}"
            alt="${escapeHTML(name)}"
            loading="lazy"
            class="platform-card-image"
            onerror="
                this.style.display='none';
                if(this.nextElementSibling)
                    this.nextElementSibling.style.display='flex';
            ">

        <div
            class="platform-card-icon"
            aria-hidden="true"
            style="display:none">
            ${icon}
        </div>

    `;

}


