/* ========================================================
   ACTION ROUTER
======================================================== */

function initializeActionRouter() {

    document.addEventListener(
        "click",
        event => {

            const element =
                event.target.closest(
                    "[data-platform-action]"
                );

            if (!element) {
                return;
            }

            const action =
                element.getAttribute(
                    "data-platform-action"
                );

            const handler =
                actions[action];

            if (
                typeof handler !==
                "function"
            ) {

                console.warn(
                    "ASEM unknown action:",
                    action
                );

                return;

            }

            event.preventDefault();
            event.stopPropagation();

            try {

                const result =
                    handler();

                if (
                    result &&
                    typeof result.then ===
                    "function"
                ) {

                    result.catch(
                        error =>
                            console.error(
                                "ASEM async action:",
                                action,
                                error
                            )
                    );

                }

            } catch (error) {

                console.error(
                    "ASEM action failed:",
                    action,
                    error
                );

            }

        }
    );

}


