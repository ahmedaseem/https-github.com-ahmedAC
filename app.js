function localSearch(query) {

    const normalized =
        String(query || "")
            .toLowerCase()
            .trim();

    const cards =
        $(
            ".platform-result-card, .project-card"
        );

    cards.forEach(card => {

        if (!normalized) {

            card.hidden =
                false;

            return;

        }

        card.hidden =
            !card.textContent
                .toLowerCase()
                .includes(normalized);

    });

}


async function remoteSearch(query) {

    if (
        !query ||
        !ASEM.api.search
    ) {
        return [];
    }

    try {

        const separator =
            ASEM.api.search.includes("?")
                ? "&"
                : "?";

        const endpoint =
            `${ASEM.api.search}${separator}q=${encodeURIComponent(query)}`;

        const data =
            await apiRequest(
                endpoint
            );

        return normalizeArray(
            data
        );

    } catch (error) {

        console.warn(
            "ASEM Global Search API:",
            error
        );

        return [];

    }

}


async function search(value) {

    const query =
        String(value || "")
            .trim();

    ASEM.state.search =
        query;

    localSearch(query);

    if (!query) {
        return [];
    }

    const remote =
        await remoteSearch(
            query
        );

    return remote;

}


